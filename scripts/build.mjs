// Build for `dsh-qq2006`.
//
// Two artifacts, both required:
//   lib/index.js  — Host half (ESM, Node). The Loader row resolves here.
//   lib/client.js — Browser half. This one is special: DSH loads it as a plain
//                   <script>, and the only thing that script may do is register
//                   a lazy factory through `window.__ModuleLoader__.load`.
//
// Why not plain ESM: the Host would execute a module that registers nothing, and
// the skin would silently never appear. Why CJS inside the factory: platform
// modules (`react`, `react/jsx-runtime`) must compile to a bare
// `require("react")` so the factory argument resolves them from DSH's frozen
// module table. An IIFE build instead emits esbuild's `__require` shim, which
// throws "Dynamic require of react is not supported" at runtime.
import { build } from 'esbuild'
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const pkg = JSON.parse(await readFile(join(ROOT, 'package.json'), 'utf8'))
const PACKAGE = pkg.name

/**
 * DSH's frozen platform module table.
 *
 * These stay external and keep their exact request names; everything else is
 * bundled. Bundling React here would create a second instance and break hooks.
 */
const PLATFORM_MODULES = [
  'react',
  'react/jsx-runtime',
  'react-dom',
  'react-dom/client',
  '@deepseek-ai/cordis',
  '@deepseek-ai/dsh-client-store',
  '@deepseek-ai/dsh-client-ui-slots',
  '@deepseek-ai/dsh-client-ui-primitives',
  '@deepseek-ai/dsh-client-ui-dockkit',
]

/** Output directory. Wiped first so stale chunks cannot leak into the package. */
const LIB = join(ROOT, 'lib')

/** Virtual module id that carries the compiled stylesheet as a string. */
const STYLE_ID = `${PACKAGE}/client.css`

/**
 * esbuild plugin: replace the `client.css` import with a JS string export.
 *
 * A dynamic bundle has no CSS pipeline; `import './client.css'` would otherwise
 * emit a sibling CSS file that nobody loads.
 * @param {string} css - compiled stylesheet text.
 * @returns {import('esbuild').Plugin} the plugin.
 */
function inlineStylesheet(css) {
  return {
    name: 'dsh-qq2006-inline-stylesheet',
    setup(builder) {
      builder.onResolve({ filter: /client\.css$/ }, (args) => {
        if (!args.importer.endsWith('index.tsx')) return undefined
        return { path: STYLE_ID, namespace: 'qq2006-style' }
      })
      builder.onLoad({ filter: /.*/, namespace: 'qq2006-style' }, () => ({
        contents: `export default ${JSON.stringify(css)};`,
        loader: 'js',
      }))
    },
  }
}

/**
 * Wrap the CJS output into the registration shell the Host expects.
 * @param {string} cjs - esbuild CJS bundle.
 * @returns {string} a script that registers one lazy factory.
 */
function wrap(cjs) {
  return `// ${PACKAGE} client bundle — generated by scripts/build.mjs, do not edit.
//
// DSH executes this file as a plain script. All it does is register a lazy
// factory; the plugin body runs when the factory is first materialized.
window.__ModuleLoader__.load({
  id: ${JSON.stringify(PACKAGE)},
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
${cjs
  .split('\n')
  .map((line) => (line.trim() === '' ? line : `    ${line}`))
  .join('\n')}
    return module.exports;
  },
});
`
}

/**
 * Fail the build instead of shipping a bundle that cannot load.
 * @param {string} source - wrapped client bundle.
 */
function assertClient(source) {
  if (!source.includes('__ModuleLoader__') || !/\.load\s*\(/.test(source)) {
    throw new Error('client.js never calls window.__ModuleLoader__.load — DSH would load a script that registers nothing')
  }
  if (!source.includes(JSON.stringify(PACKAGE))) {
    throw new Error(`client.js does not register id ${PACKAGE} — the Host indexes factories by package name`)
  }
  if (!/factory:\s*\(?\s*require\s*\)?\s*=>/.test(source) && !/factory\s*\(\s*require\s*\)/.test(source)) {
    throw new Error('client.js factory is not parameterized by `require` — platform modules cannot resolve')
  }
  if (source.includes('Dynamic require of')) {
    throw new Error('client.js contains esbuild\'s __require shim — the client build must be format: "cjs"')
  }
  if (/^\s*export\s/m.test(source) || /^\s*import\s+[^(]/m.test(source)) {
    throw new Error('client.js contains top-level ESM syntax — DSH loads it as a classic script')
  }
  if (source.includes('Symbol.for("react.element")') || source.includes('react.production.min.js')) {
    throw new Error('client.js appears to bundle React — platform modules must stay external')
  }
}

await rm(LIB, { recursive: true, force: true })
await mkdir(LIB, { recursive: true })

// --- Host half ------------------------------------------------------------
await build({
  entryPoints: [join(ROOT, 'src/host/index.ts')],
  outfile: join(LIB, 'index.js'),
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  packages: 'external',
  sourcemap: false,
  logLevel: 'warning',
})

// --- Client half ----------------------------------------------------------
const css = await readFile(join(ROOT, 'src/client/client.css'), 'utf8')
if (css.trim() === '') throw new Error('src/client/client.css is empty')

const intermediate = join(LIB, '.client.cjs')
await build({
  entryPoints: [join(ROOT, 'src/client/index.tsx')],
  outfile: intermediate,
  bundle: true,
  platform: 'browser',
  format: 'cjs',
  target: 'es2022',
  jsx: 'automatic',
  jsxImportSource: 'react',
  external: PLATFORM_MODULES,
  loader: { '.png': 'dataurl', '.gif': 'dataurl' },
  minify: true,
  legalComments: 'none',
  logLevel: 'warning',
  define: { 'process.env.NODE_ENV': '"production"' },
  plugins: [inlineStylesheet(css)],
})

const wrapped = wrap(await readFile(intermediate, 'utf8'))
assertClient(wrapped)
await writeFile(join(LIB, 'client.js'), wrapped)
await rm(intermediate, { force: true })

const kb = (Buffer.byteLength(wrapped) / 1024).toFixed(1)
console.log(`built lib/index.js and lib/client.js (${kb} KiB, stylesheet + artwork inlined)`)
